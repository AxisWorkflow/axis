class SurfaceError(ValueError):
    """Stable machine code and a safe field label; never echo raw identities."""
    def __init__(self, code: str, field: str = ""):
        self.code = code
        self.field = field
        super().__init__(code + (": " + field if field else ""))


def _require(condition: bool, code: str, field: str = "") -> None:
    if not condition:
        raise SurfaceError(code, field)


def _in_unicode_ranges(code_point: int, ranges: tuple[tuple[int, int], ...]) -> bool:
    return any(low <= code_point <= high for low, high in ranges)


def _strip_white_space(value: str) -> str:
    """Strip only the frozen Unicode 16 White_Space property, for syntax."""
    start, end = 0, len(value)
    while start < end and _in_unicode_ranges(ord(value[start]), _EDGE_WHITE_SPACE_RANGES):
        start += 1
    while end > start and _in_unicode_ranges(ord(value[end - 1]), _EDGE_WHITE_SPACE_RANGES):
        end -= 1
    return value[start:end]


def _safe_scalar_text(value: object, field: str, *, max_bytes: int,
                      max_scalars: int | None = None, nonblank: bool = True) -> str:
    _require(type(value) is str, "invalid_string", field)
    _require(len(value) <= (max_bytes if max_scalars is None else max_scalars),
             "string_limit", field)
    # Cs is rejected before UTF-8 encoding. No ambient Unicode database is used.
    _require(not any(_in_unicode_ranges(ord(c), _FORBIDDEN_UNICODE_RANGES) for c in value),
             "unsafe_unicode", field)
    _require(len(value.encode("utf-8")) <= max_bytes and
             (max_scalars is None or len(value) <= max_scalars), "string_limit", field)
    if nonblank:
        trimmed = _strip_white_space(value)
        _require(bool(value) and bool(trimmed), "blank_identifier", field)
        _require(value == trimmed, "identifier_whitespace", field)
    return value


def _identifier(value: object, field: str) -> str:
    value = _safe_scalar_text(value, field, max_bytes=ID_BYTES, max_scalars=ID_SCALARS)
    _require(not any(c in _GLOB for c in value), "wildcard_identifier", field)
    return value


def canonical_role(value: object) -> str | None:
    """Existing display-name aliases, not an authorization check."""
    if type(value) is not str:
        return None
    return _ROLE_ALIASES.get(re.sub(r"\s+", "", value).lower())


@dataclass(frozen=True)
class SurfaceRow:
    schema: int
    surface: str
    role: str
    read_scope: str | tuple[str, ...]
    host_binding: str | None


@dataclass(frozen=True)
class SurfaceTable:
    schema: int
    rows: tuple[SurfaceRow, ...]

    def get(self, surface: str) -> SurfaceRow | None:
        """Exact lookup; no wildcard, fallback, authentication or admission."""
        return next((row for row in self.rows if row.surface == surface), None)


def _table_text(text: object) -> str:
    _require(type(text) is str, "surface_text")
    _require(len(text) <= TABLE_BYTES, "surface_table_limit")
    try:
        size = len(text.encode("utf-8"))
    except UnicodeEncodeError:
        raise SurfaceError("unsafe_unicode", "surface_table") from None
    _require(size <= TABLE_BYTES, "surface_table_limit")
    return text


def _schema(text: str) -> int:
    markers = []
    first_table = None
    # Detection only: retain original offsets while exposing a hidden label.
    # Keep LF (and thus CRLF) as physical boundaries. LS/PS also need detection
    # because splitlines() would otherwise divide an obscured declaration.
    visible = [(i, c) for i, c in enumerate(text) if c == "\n" or not (
        _in_unicode_ranges(ord(c), _FORBIDDEN_UNICODE_RANGES) or c in "\u2028\u2029")]
    breaks = "\n\r\v\f\x1c\x1d\x1e\x85\u2028\u2029"
    for match in re.finditer("surface-schema", "".join(c for _, c in visible), re.I | re.A):
        start = visible[match.start()][0]
        prefix = start
        while prefix and text[prefix - 1] not in breaks and (
            text[prefix - 1].isspace() or
            _in_unicode_ranges(ord(text[prefix - 1]), _FORBIDDEN_UNICODE_RANGES)):
            prefix -= 1
        if prefix and text[prefix - 1] not in breaks:
            continue  # Ordinary prose containing the label is not a declaration.
        _require(not text[prefix:start].strip() and
                 text[start:start + len("surface-schema")].lower() == "surface-schema",
                 "surface_schema_invalid")
    for index, line in enumerate(text.splitlines()):
        if line.lstrip().startswith("|") and first_table is None:
            first_table = index
        # A schema-like field cannot silently become legacy on a spelling/value error.
        if line.lstrip().lower().startswith("surface-schema"):
            markers.append((index, line.strip()))
    if not markers:
        return 1
    _require(len(markers) == 1, "surface_schema_duplicate")
    index, marker = markers[0]
    match = re.fullmatch(r"surface-schema: ([12])", marker)
    _require(match is not None, "surface_schema_invalid")
    _require(first_table is None or index < first_table, "surface_schema_position")
    return int(match.group(1))


def parse_surface_table(text: str | None) -> SurfaceTable:
    """Missing/unmarked input is schema 1; an explicit bad marker always fails.

    Schema 1 preserves the old parser's accepted semantics. Schema 2 is strict.
    A schema-2 Main row is data only, and requires an OpenClaw fingerprint.
    """
    if text is None:
        return SurfaceTable(1, ())
    text = _table_text(text)
    schema = _schema(text)
    return _legacy_table(text) if schema == 1 else _strict_table(text)


def _legacy_table(text: str) -> SurfaceTable:
    # Own pure reimplementation of the old algorithm; Candidate is never imported.
    rows: list[SurfaceRow] = []
    names = set()
    header_seen = False
    for line in text.splitlines():
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if not header_seen:
            _require([c.lower() for c in cells] == ["surface", "role", "read scope"],
                     "surface_table_invalid")
            header_seen = True
            continue
        if all(set(cell) <= set("-: ") for cell in cells):
            continue
        _require(len(cells) == 3, "surface_table_invalid")
        name, raw_role, scope = cells
        name = name.strip("`")
        role = canonical_role(raw_role.strip("`"))
        _require(_SURFACE.fullmatch(name) is not None and role in DECLARABLE and name not in names,
                 "surface_table_invalid")
        if scope.lower() == "project":
            folders: str | tuple[str, ...] = "project"
        else:
            folders = tuple(f.strip().strip("`").rstrip("/") for f in scope.split(",") if f.strip())
            _require(bool(folders) and all(_FOLDER.fullmatch(f) for f in folders), "surface_table_invalid")
        _require(folders != "project" or role in _USER_ONLY, "surface_scope_required")
        rows.append(SurfaceRow(1, name, role, folders, None))
        names.add(name)
    return SurfaceTable(1, tuple(rows))


def _cell(value: str) -> str:
    # Single inline-code wrapping is syntax. IDs inside it remain exact.
    if value.startswith("`") or value.endswith("`"):
        _require(len(value) >= 2 and value[0] == value[-1] == "`" and "`" not in value[1:-1],
                 "surface_table_invalid")
        return value[1:-1]
    _require("`" not in value, "surface_table_invalid")
    return value


def _scope(value: str, role: str) -> str | tuple[str, ...]:
    if value == "project":
        _require(role in _USER_ONLY, "surface_scope_required")
        return "project"
    raw_folders = value.split(",")
    _require(1 <= len(raw_folders) <= MAX_FOLDERS, "surface_scope_limit")
    folders = []
    for raw in raw_folders:
        folder = _cell(_strip_white_space(raw))
        # Retain the existing friendly single trailing folder slash.
        if folder.endswith("/"):
            folder = folder[:-1]
        _require(folder == _strip_white_space(folder) and _FOLDER.fullmatch(folder) is not None,
                 "surface_table_invalid")
        _require(folder not in folders, "surface_scope_duplicate")
        folders.append(folder)
    return tuple(folders)


def _strict_table(text: str) -> SurfaceTable:
    """One contiguous pipe-bearing block; pipe-free lines end it.

    Pipe-free prose is allowed around the block. Any later pipe-bearing line
    refuses, including a resumed row or a second table. Empty tables remain
    valid. LF and CRLF delimit lines; other line separators are invalid in rows.
    """
    lines = []
    ended = False
    raw_lines = text.split("\n")
    for index, raw_line in enumerate(raw_lines):
        # A single CR immediately before LF is CRLF syntax, not cell content.
        line = raw_line[:-1] if index < len(raw_lines) - 1 and raw_line.endswith("\r") else raw_line
        if "|" not in line:
            if lines:
                ended = True
            continue
        _require(not ended, "surface_table_invalid")
        _safe_scalar_text(line, "surface_row", max_bytes=TABLE_BYTES, nonblank=False)
        _require("\u2028" not in line and "\u2029" not in line, "surface_table_invalid")
        clean_line = _strip_white_space(line)
        _require(line.startswith("|") and clean_line.endswith("|"), "surface_table_invalid")
        cells = [_strip_white_space(part) for part in clean_line[1:-1].split("|")]
        _require(len(cells) == 4, "surface_table_invalid")
        lines.append(cells)
    _require(len(lines) >= 2, "surface_table_invalid")
    _require(lines[0] == ["Surface", "Role", "Read scope", "Host binding"], "surface_table_invalid")
    _require(all(re.fullmatch(r":?-{3,}:?", cell) is not None for cell in lines[1]), "surface_table_invalid")
    _require(len(lines) - 2 <= MAX_ROWS, "surface_row_limit")
    rows = []
    names, bindings = set(), set()
    for raw_name, raw_role, raw_scope, raw_binding in lines[2:]:
        name, role_text, binding = _cell(raw_name), _cell(raw_role), _cell(raw_binding)
        # Role display aliases keep their existing meaning, with fixed whitespace.
        role = _ROLE_ALIASES.get("".join(c for c in role_text if not
            _in_unicode_ranges(ord(c), _EDGE_WHITE_SPACE_RANGES)).lower())
        _require(_SURFACE.fullmatch(name) is not None and name not in names, "surface_table_invalid")
        _require(role in DECLARABLE or role == "Main", "surface_table_invalid")
        scope = _scope(raw_scope, role)
        _require(binding == "manual" or _BINDING.fullmatch(binding) is not None, "surface_binding_invalid")
        _require(role != "Main" or binding != "manual", "main_binding_required")
        if binding != "manual":
            _require(binding not in bindings, "surface_binding_duplicate")
            bindings.add(binding)
        rows.append(SurfaceRow(2, name, role, scope, binding))
        names.add(name)
    return SurfaceTable(2, tuple(rows))


def _json_bytes(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode("utf-8")


def _participants(values: object, owner: str, kind: str) -> tuple[str, ...]:
    _require(type(values) in (list, tuple) and len(values) <= MAX_PARTICIPANTS,
             "participant_limit", "participantSenderIds")
    participants = tuple(_identifier(value, "participantSenderIds") for value in values)
    _require(len(set(participants)) == len(participants), "participant_duplicate")
    _require(owner not in participants, "owner_in_participants")
    _require(kind != "direct" or not participants, "direct_participants")
    # Python scalar string ordering is Unicode code-point order; never normalize.
    return tuple(sorted(participants))


def binding_payload(project_id: str, instance_id: str, agent_id: str, channel: str,
                    account_id: str, chat_id: str, kind: str, owner_sender_id: str,
                    participant_sender_ids: tuple[str, ...] | list[str]) -> bytes:
    """Exact UTF-8 compact JSON bytes of the original fixed binding array."""
    values = [_identifier(value, field) for value, field in (
        (project_id, "projectId"), (instance_id, "instanceId"), (agent_id, "agentId"),
        (channel, "channel"), (account_id, "accountId"), (chat_id, "chatId"),
        (kind, "kind"), (owner_sender_id, "ownerSenderId"))]
    _require(kind in ("direct", "group"), "chat_kind")
    participants = _participants(participant_sender_ids, owner_sender_id, kind)
    return _json_bytes([BINDING_TAG, *values, participants])


def binding_fingerprint(project_id: str, instance_id: str, agent_id: str, channel: str,
                        account_id: str, chat_id: str, kind: str, owner_sender_id: str,
                        participant_sender_ids: tuple[str, ...] | list[str]) -> str:
    payload = binding_payload(project_id, instance_id, agent_id, channel, account_id,
                              chat_id, kind, owner_sender_id, participant_sender_ids)
    return BINDING_PREFIX + hashlib.sha256(payload).hexdigest()


def policy_payload(row: SurfaceRow) -> bytes:
    """Exact UTF-8 compact JSON [tag,binding,surface,canonicalRoleName,readScope].

    Only strict host rows have a chat policy. Manual/legacy rows have no digest.
    Validation is repeated because callers may construct a dataclass themselves.
    """
    _require(type(row) is SurfaceRow and type(row.schema) is int and row.schema == 2,
             "policy_row_schema")
    _require(type(row.host_binding) is str and _BINDING.fullmatch(row.host_binding) is not None,
             "surface_binding_invalid")
    _require(type(row.surface) is str and _SURFACE.fullmatch(row.surface) is not None,
             "surface_table_invalid")
    _require(type(row.role) is str and row.role in DECLARABLE | {"Main"}, "policy_role")
    scope = row.read_scope
    if type(scope) is str:
        _require(scope == "project" and row.role in _USER_ONLY, "surface_scope_required")
    else:
        _require(type(scope) is tuple and 1 <= len(scope) <= MAX_FOLDERS, "surface_scope_limit")
        _require(all(type(f) is str and f == _strip_white_space(f) and _FOLDER.fullmatch(f) for f in scope),
                 "surface_table_invalid")
        _require(len(set(scope)) == len(scope), "surface_scope_duplicate")
    return _json_bytes([POLICY_TAG, row.host_binding, row.surface, row.role, scope])


def policy_digest(row: SurfaceRow) -> str:
    """Lowercase hex SHA-256 of policy_payload; a consistency key, not a grant."""
    return hashlib.sha256(policy_payload(row)).hexdigest()


def _object(value: object, keys: set[str], field: str, *, optional: set[str] = frozenset()) -> dict:
    _require(type(value) is dict and set(value) <= keys | optional and keys <= set(value),
             "config_keys", field)
    return value


def _array(value: object, field: str, limit: int, minimum: int = 0) -> list:
    _require(type(value) is list and minimum <= len(value) <= limit, "config_array", field)
    return value


def _workspace(value: object) -> str:
    value = _safe_scalar_text(value, "workspaceDir", max_bytes=WORKSPACE_BYTES)
    _require(not any(c in _GLOB for c in value), "workspace_invalid")
    # Lexical only. No filesystem lookup, normalization, expansion, or cwd fallback.
    if value.startswith("/") and not value.startswith("//"):
        _require("\\" not in value, "workspace_invalid")
        parts = value[1:].split("/")
    elif re.match(r"[A-Za-z]:\\", value):
        _require("/" not in value, "workspace_invalid")
        parts = value[3:].split("\\")
    elif value.startswith("\\\\"):
        _require("/" not in value, "workspace_invalid")
        parts = value[2:].split("\\")
        _require(len(parts) >= 2, "workspace_invalid")
    else:
        raise SurfaceError("workspace_invalid")
    _require(all(part and part not in (".", "..") and part == _strip_white_space(part) for part in parts),
             "workspace_invalid")
    return value


def _json_load(raw: object) -> object:
    _require(type(raw) in (str, bytes), "config_text")
    if type(raw) is bytes:
        _require(len(raw) <= CONFIG_BYTES, "config_size")
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError:
            raise SurfaceError("config_encoding") from None
    else:
        _require(len(raw) <= CONFIG_BYTES, "config_size")
        try:
            _require(len(raw.encode("utf-8")) <= CONFIG_BYTES, "config_size")
        except UnicodeEncodeError:
            raise SurfaceError("config_encoding") from None
        text = raw
    # Reject excessive nesting before the decoder allocates its object tree.
    depth, quoted, escape = 0, False, False
    for char in text:
        if quoted:
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == '"':
                quoted = False
        elif char == '"':
            quoted = True
        elif char in "[{":
            depth += 1
            _require(depth <= JSON_DEPTH, "config_depth")
        elif char in "]}":
            depth -= 1
    def pairs(items):
        obj = {}
        for key, value in items:
            _require(key not in obj, "config_duplicate_key")
            obj[key] = value
        return obj
    def constant(_):
        raise SurfaceError("config_json")
    try:
        return json.loads(text, object_pairs_hook=pairs, parse_constant=constant)
    except (ValueError, RecursionError) as error:
        if isinstance(error, SurfaceError):
            raise
        raise SurfaceError("config_json") from None


@dataclass(frozen=True)
class Chat:
    surface: str
    channel: str
    account_id: str
    chat_id: str
    kind: str
    owner_sender_id: str
    participant_sender_ids: tuple[str, ...]
    binding: str


@dataclass(frozen=True)
class Agent:
    agent_id: str
    project_id: str
    workspace_dir: str
    chats: tuple[Chat, ...]


@dataclass(frozen=True)
class ChatPolicy:
    schema: str
    instance_id: str
    agents: tuple[Agent, ...]
    legacy_agents: tuple[tuple[str, tuple[str, ...]], ...]

    def get_chat(self, agent_id: str, channel: str, account_id: str, chat_id: str) -> Chat | None:
        """Exact configured route lookup; no requester or host authentication."""
        for agent in self.agents:
            if agent.agent_id == agent_id:
                return next((chat for chat in agent.chats if
                    (chat.channel, chat.account_id, chat.chat_id) == (channel, account_id, chat_id)), None)
        return None


def parse_plugin_config(raw: str | bytes) -> ChatPolicy | None:
    """Parse full JSON plugin config. Absence of chatPolicy returns None.

    None selects the unchanged legacy consumer; null/bad strict data raises.
    With a strict stanza, all config keys, legacy/strict IDs and routes are exact,
    bounded and duplicate-free. No role/scope/owner boolean is accepted as input.
    """
    config = _json_load(raw)
    _require(type(config) is dict, "config_object")
    if "chatPolicy" not in config:
        # Leave the legacy plugin's own schema/role-list behavior to that plugin.
        return None
    _object(config, {"chatPolicy"}, "plugin", optional=set(LEGACY_KEYS))
    policy = _object(config["chatPolicy"], {"schema", "instanceId", "agents"}, "chatPolicy")
    _require(policy["schema"] == CONFIG_TAG, "config_schema")
    instance = _identifier(policy["instanceId"], "instanceId")
    legacy = []
    legacy_ids = set()
    for key in LEGACY_KEYS:
        ids = tuple(_identifier(value, key) for value in _array(config.get(key, []), key, MAX_AGENTS))
        _require(len(ids) == len(set(ids)) and not legacy_ids.intersection(ids), "legacy_agent_duplicate")
        legacy_ids.update(ids)
        legacy.append((key, ids))
    agents, agent_ids, routes, surfaces, bindings = [], set(), set(), set(), set()
    project_roots, root_projects = {}, {}
    total_chats = 0
    for raw_agent in _array(policy["agents"], "agents", MAX_AGENTS, minimum=1):
        entry = _object(raw_agent, {"agentId", "projectId", "workspaceDir", "chats"}, "agent")
        agent_id = _identifier(entry["agentId"], "agentId")
        project_id = _identifier(entry["projectId"], "projectId")
        workspace = _workspace(entry["workspaceDir"])
        _require(agent_id not in agent_ids and agent_id not in legacy_ids, "agent_duplicate")
        _require(project_id not in project_roots or project_roots[project_id] == workspace,
                 "project_workspace_conflict")
        _require(workspace not in root_projects or root_projects[workspace] == project_id,
                 "workspace_project_conflict")
        project_roots[project_id], root_projects[workspace] = workspace, project_id
        agent_ids.add(agent_id)
        chats = []
        for raw_chat in _array(entry["chats"], "chats", MAX_CHATS_PER_AGENT):
            total_chats += 1
            _require(total_chats <= MAX_CHATS, "chat_total_limit")
            item = _object(raw_chat, {"surface", "channel", "accountId", "chatId", "kind",
                                     "ownerSenderId", "participantSenderIds"}, "chat")
            surface = item["surface"]
            _require(type(surface) is str and _SURFACE.fullmatch(surface) is not None, "surface_name")
            channel = _identifier(item["channel"], "channel")
            account = _identifier(item["accountId"], "accountId")
            chat_id = _identifier(item["chatId"], "chatId")
            kind = item["kind"]
            _require(type(kind) is str and kind in ("direct", "group"), "chat_kind")
            owner = _identifier(item["ownerSenderId"], "ownerSenderId")
            _array(item["participantSenderIds"], "participantSenderIds", MAX_PARTICIPANTS)
            participants = _participants(item["participantSenderIds"], owner, kind)
            route = (agent_id, channel, account, chat_id)
            surface_key = (project_id, surface)
            _require(route not in routes, "route_duplicate")
            _require(surface_key not in surfaces, "config_surface_duplicate")
            binding = binding_fingerprint(project_id, instance, agent_id, channel, account,
                                          chat_id, kind, owner, participants)
            _require(binding not in bindings, "config_binding_duplicate")
            routes.add(route)
            surfaces.add(surface_key)
            bindings.add(binding)
            chats.append(Chat(surface, channel, account, chat_id, kind, owner, participants, binding))
        agents.append(Agent(agent_id, project_id, workspace, tuple(chats)))
    return ChatPolicy(CONFIG_TAG, instance, tuple(agents), tuple(legacy))


def check_declaration(chat: Chat, table: SurfaceTable) -> SurfaceRow:
    """Pure consistency check only; success is not authenticated admission.

    Main/Assistant/Auxiliary require a configured direct route here. Authentic
    direct peer, current sender, run identity and all lifecycle checks remain
    outside this module. A model can manufacture matching inputs to this check.
    """
    _require(type(chat) is Chat and type(table) is SurfaceTable and table.schema == 2,
             "strict_schema_required")
    row = table.get(chat.surface)
    _require(row is not None, "surface_missing")
    policy_payload(row)
    _require(row.host_binding == chat.binding, "binding_mismatch")
    _require(row.role not in _USER_ONLY or chat.kind == "direct", "direct_route_required")
    return row
